package com.filmexposure.domain.model

/**
 * Точки линейного слайдера дистанции фокусировки (§8.4, отменяет старый лог-драг по боковой
 * панели ГРИП). Динамический шаг под макро-зону советской оптики (напр. Гелиос-44 на f/2 —
 * ГРИП на 1м всего ~3см, ошибка фокусировки там фатальна):
 *  - 1.0–2.9м, шаг 0.1м
 *  - 3.0–6.5м, шаг 0.5м
 *  - 7.0–20.0м, шаг 1м
 *  - последняя точка — Бесконечность (∞)
 *
 * Явный список точек, а не формула "шаг по значению на лету" — чтобы Slider (дискретный, по
 * индексу) и текстовое отображение дистанции всегда указывали ровно на одно и то же значение.
 *
 * НЕ ПОДТВЕРЖДЕНО пользователем (рабочее допущение, см. память проекта):
 *  - нижняя граница = 1м, макро-зоны тоньше 1м нет;
 *  - после 20м следующая точка сразу ∞, без промежуточных отметок.
 */
object FocusDistanceStops {
    val METERS: List<Float> = buildList {
        var d = 1.0f
        while (d < 3.0f - 1e-4f) { add(d); d += 0.1f }
        d = 3.0f
        while (d < 7.0f - 1e-4f) { add(d); d += 0.5f }
        d = 7.0f
        while (d < 20f - 1e-4f) { add(d); d += 1.0f }
        add(20.0f)
        add(Float.POSITIVE_INFINITY)
    }

    /** Дефолт при запуске — 3м (решение по проекту), ищется по значению, а не хардкод-индексом,
     *  чтобы не съехать молча при будущей правке границ/шага диапазонов. */
    val DEFAULT_INDEX: Int = METERS.indexOfFirst { it == 3.0f }
        .also { check(it >= 0) { "3.0м отсутствует в FocusDistanceStops.METERS — дефолт сломан" } }
}
